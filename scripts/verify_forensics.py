import os
import subprocess
import json

def run_cmd(command, cwd=None):
    print(f"Running command: {command}")
    res = subprocess.run(command, shell=True, capture_output=True, text=True, cwd=cwd)
    if res.returncode != 0:
        print(f"Error executing command: {res.stderr}")
    return res

def main():
    base_dir = "/workspace"
    dataset_dir = os.path.join(base_dir, "dataset")
    capture_dir = os.path.join(base_dir, "capture")
    
    os.makedirs(capture_dir, exist_ok=True)
    
    pcap_file = os.path.join(dataset_dir, "evilprogram.pcap")
    if not os.path.exists(pcap_file):
        print(f"ERROR: {pcap_file} does not exist inside the container.")
        return
        
    print("=== Step 1: Running TShark Packet Check ===")
    tshark_cmd = f"tshark -r {pcap_file} -c 5"
    res = run_cmd(tshark_cmd)
    if res.returncode == 0:
        print("TShark successfully parsed the PCAP file.")
        print("Sample output:\n", res.stdout)
    else:
        print("TShark execution failed.")

    print("\n=== Step 2: Running Zeek connection logs generation ===")
    zeek_out_dir = os.path.join(capture_dir, "zeek_logs")
    os.makedirs(zeek_out_dir, exist_ok=True)
    zeek_cmd = f"zeek -r {pcap_file}"
    res = run_cmd(zeek_cmd, cwd=zeek_out_dir)
    if res.returncode == 0:
        print("Zeek successfully processed the PCAP file.")
        log_files = os.listdir(zeek_out_dir)
        print(f"Generated Zeek log files: {log_files}")
    else:
        print("Zeek execution failed.")

    print("\n=== Step 3: Running Suricata alerts check ===")
    suricata_out_dir = os.path.join(capture_dir, "suricata_logs")
    os.makedirs(suricata_out_dir, exist_ok=True)
    
    # Run Suricata against PCAP using default configs (disable checksum checks to prevent ignoring packets)
    suricata_cmd = f"suricata -r {pcap_file} -l {suricata_out_dir} -k none"
    res = run_cmd(suricata_cmd)
    if res.returncode == 0:
        print("Suricata successfully processed the PCAP file.")
        eve_json_path = os.path.join(suricata_out_dir, "eve.json")
        if os.path.exists(eve_json_path):
            print("OK: eve.json generated by Suricata.")
            # Read first few lines of eve.json to check alerts or events
            events_count = 0
            alerts_count = 0
            with open(eve_json_path, 'r') as f:
                for line in f:
                    event = json.loads(line)
                    events_count += 1
                    if event.get("event_type") == "alert":
                        alerts_count += 1
            print(f"Total processed events in eve.json: {events_count}")
            print(f"Total intrusion alerts triggered: {alerts_count}")
        else:
            print("WARNING: eve.json not found in Suricata output directory.")
    else:
        print("Suricata execution failed.")

if __name__ == "__main__":
    main()
